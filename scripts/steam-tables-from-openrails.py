#!/usr/bin/env python3
"""Open Rails' steam tables as C++ data (task driving 04).

Reads Open Rails' Orts.Simulation/Common/SteamTable.cs and writes
src/tsre/sim/steam/SteamTablesData.inc: its arrays as written (in its units,
named by them), its tables (Interpolator: an x array and a y array) and its
2D tables (Interpolator2D: x values, one table for each). The data are
steam properties and empirical charts (boiler efficiency, injectors); the
C++ in src/tsre/sim/steam reads them by name.

Usage: steam-tables-from-openrails.py <Open Rails Source folder> [output]
"""
import re
import sys
from pathlib import Path

ARRAY = re.compile(r"static\s+float\[\]\s+(\w+)\s*=\s*new\s+float\[\]\s*\{(.*?)\}\s*;", re.S)
TABLE = re.compile(r"public\s+static\s+Interpolator\s+(\w+)\s*\(\s*\)\s*\{\s*return\s+new\s+Interpolator\s*"
                   r"\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*;\s*\}", re.S)
LIST = re.compile(r"static\s+Interpolator\[\]\s+(\w+)\s*=\s*new\s+Interpolator\[\]\s*\{(.*?)\}\s*;", re.S)
TABLE2D = re.compile(r"public\s+static\s+Interpolator2D\s+(\w+)\s*\(\s*\)\s*\{\s*return\s+new\s+Interpolator2D\s*"
                     r"\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*;\s*\}", re.S)
NUMBER = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?[fF]?$")


def values(body, name):
    body = re.sub(r"//[^\n]*", "", body)
    out = []
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        if not NUMBER.match(item):
            sys.exit("%s: not a number: %r" % (name, item))
        out.append(item.rstrip("fF"))
    return out


def main():
    source = Path(sys.argv[1]) / "Orts.Simulation" / "Common" / "SteamTable.cs"
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else \
        Path(__file__).resolve().parent.parent / "src" / "tsre" / "sim" / "steam" / "SteamTablesData.inc"
    text = source.read_text(encoding="utf-8-sig")
    code = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    code = re.sub(r"//[^\n]*", "", code)
    arrays = {name: values(body, name) for name, body in ARRAY.findall(code)}
    tables = TABLE.findall(code)
    lists = {name: re.findall(r"(\w+)\s*\(\s*\)", body) for name, body in LIST.findall(code)}
    tables2d = TABLE2D.findall(code)
    known = {name for name, _, _ in tables}
    for name, x, y in tables:
        for array in (x, y):
            if array not in arrays:
                sys.exit("%s: no array %s" % (name, array))
        if len(arrays[x]) != len(arrays[y]):
            sys.exit("%s: %d x values, %d y values" % (name, len(arrays[x]), len(arrays[y])))
    for name, x, rows in tables2d:
        if x not in arrays or rows not in lists:
            sys.exit("%s: no %s or %s" % (name, x, rows))
        missing = [t for t in lists[rows] if t not in known]
        if missing:
            sys.exit("%s: unknown tables %s" % (name, missing))
        if len(lists[rows]) != len(arrays[x]):
            sys.exit("%s: %d x values, %d tables" % (name, len(arrays[x]), len(lists[rows])))

    out = ["// Generated by scripts/steam-tables-from-openrails.py from Open Rails'",
           "// Orts.Simulation/Common/SteamTable.cs: its arrays as written, in the units",
           "// their names give, its tables and 2D tables. Do not edit.", ""]
    for name, items in arrays.items():
        out.append("const double %s[] = {%s};" % (name, ", ".join(items)))
    out.append("")
    out.append("const Table1DData Tables1D[] = {")
    for name, x, y in tables:
        out.append('    {"%s", %s, %s, %d},' % (name, x, y, len(arrays[x])))
    out.append("};")
    out.append("")
    for name, x, rows in tables2d:
        out.append("const char *const %s_Rows[] = {%s};" % (name, ", ".join('"%s"' % t for t in lists[rows])))
    out.append("const Table2DData Tables2D[] = {")
    for name, x, rows in tables2d:
        out.append('    {"%s", %s, %s_Rows, %d},' % (name, x, name, len(arrays[x])))
    out.append("};")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out) + "\n")
    print("%d arrays, %d tables, %d 2D tables into %s" % (len(arrays), len(tables), len(tables2d), output))


if __name__ == "__main__":
    main()
